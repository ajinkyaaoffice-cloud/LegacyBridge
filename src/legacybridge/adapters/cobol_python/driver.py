"""Generate a COBOL test driver for a CALLed subprogram.

The driver reads stdin line by line (format: iofmt.call_layout), MOVEs each field into the
subprogram's parameter records, CALLs it, MOVEs every field back into an output record of the
same layout and DISPLAYs it. WORKING-STORAGE of the subprogram persists across lines, exactly as
it would across CALLs in production. The exit code is RETURN-CODE at STOP RUN.
"""

from __future__ import annotations

from .iofmt import Layout
from .parser import DataItem, ModuleInfo

DRIVER_ID = "LBDRIVER"


def _decl(item: DataItem, depth: int = 0) -> list[str]:
    parts = [f"{item.level:02d}", item.name]
    if item.redefines:
        parts += ["REDEFINES", item.redefines]
    if item.pic:
        parts += ["PIC", item.pic]
    if item.usage and item.usage != "DISPLAY":
        parts.append(item.usage)
    if item.sign_separate:
        parts.append("SIGN LEADING SEPARATE")
    if item.justified:
        parts.append("JUSTIFIED RIGHT")
    if item.occurs:
        parts += ["OCCURS", str(item.occurs)]
    lines = ["  " * depth + " ".join(parts) + "."]
    for child in item.children:
        lines += _decl(child, depth + 1)
    return lines


def generate_driver(info: ModuleInfo, layout: Layout) -> str:
    """COBOL source (free format) of the driver for subprogram `info`."""
    rec = layout.records[0]
    n = rec.length
    i_fields, o_fields = [], []
    for idx, f in enumerate(rec.fields, 1):
        i_fields.append(f"   05 LB-I-{idx:04d} PIC {f.text_pic()}.")
        o_fields.append(f"   05 LB-O-{idx:04d} PIC {f.text_pic()}.")
        if idx < len(rec.fields):
            i_fields.append("   05 FILLER PIC X.")
            o_fields.append("   05 FILLER PIC X VALUE '|'.")
    params = info.linkage_params()
    decls = [ln for p in params for ln in _decl(p)]
    moves_in = [f"    MOVE LB-I-{i:04d} TO {f.qualified()}" for i, f in enumerate(rec.fields, 1)]
    moves_out = [f"    MOVE {f.qualified()} TO LB-O-{i:04d}" for i, f in enumerate(rec.fields, 1)]
    using = " ".join(layout.params)
    return "\n".join([
        ">>SOURCE FORMAT FREE",
        "*> Generated by LegacyBridge: differential-test driver for " + info.name,
        "IDENTIFICATION DIVISION.",
        f"PROGRAM-ID. {DRIVER_ID}.",
        "ENVIRONMENT DIVISION.",
        "INPUT-OUTPUT SECTION.",
        "FILE-CONTROL.",
        "    SELECT LB-IN ASSIGN TO KEYBOARD ORGANIZATION IS LINE SEQUENTIAL",
        "        FILE STATUS IS LB-FS.",
        "DATA DIVISION.",
        "FILE SECTION.",
        "FD LB-IN.",
        f"01 LB-IN-REC PIC X({n}).",
        "WORKING-STORAGE SECTION.",
        "01 LB-FS PIC XX.",
        "01 LB-EOF PIC X VALUE 'N'.",
        "01 LB-I.",
        *i_fields,
        "01 LB-O.",
        *o_fields,
        *decls,
        "PROCEDURE DIVISION.",
        "LB-MAIN.",
        "    OPEN INPUT LB-IN",
        "    PERFORM UNTIL LB-EOF = 'Y'",
        "        READ LB-IN INTO LB-I",
        "            AT END MOVE 'Y' TO LB-EOF",
        "            NOT AT END PERFORM LB-CALL",
        "        END-READ",
        "    END-PERFORM",
        "    CLOSE LB-IN",
        "    STOP RUN.",
        "LB-CALL.",
        *moves_in,
        f"    CALL '{info.name}' USING {using}",
        *moves_out,
        "    DISPLAY LB-O.",
        "",
    ])
