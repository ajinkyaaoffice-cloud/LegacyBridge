"""Generate the Python-side test harness for a translated module (mirror of driver.py).

Subprograms: read stdin lines in the driver's '|'-separated format, build one dict per USING
parameter (keys = COBOL elementary field names, values Decimal / str), call the translated
function, then print the same layout from the (mutated) dicts. Formatting is STRICT: a numeric
value that a COBOL field could not hold (too many digits or decimals, a sign on an unsigned field,
a float) prints as '!' * width, so translations that forget COBOL store semantics fail loudly.

Mains: call `main()`; its int return value is the exit code (RETURN-CODE).
"""

from __future__ import annotations

import pprint

from .iofmt import Layout


def param_keys(layout: Layout) -> list[tuple[str, str]]:
    """(param, dict key) for every field: leaf name, or GROUP.LEAF when the leaf repeats in a param."""
    fields = layout.records[0].fields
    out = []
    for f in fields:
        same = [g for g in fields if g.param == f.param and g.name == f.name]
        key = f.name if len(same) == 1 else ".".join([*f.f.path[1:], f.name])
        out.append((f.param, key))
    return out


HARNESS_CALL = r'''# Generated by LegacyBridge - differential-test harness for {module}. Do not edit.
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from decimal import Decimal
sys.setrecursionlimit(10000)

SPEC = {spec}
PARAMS = {params}

def _parse(f, text):
    if f["kind"] != "numeric":
        return text
    sign = -1 if f["signed"] and text[:1] == "-" else 1
    body = text[1:] if f["signed"] else text
    return (Decimal(int(body or "0")) * sign).scaleb(-f["scale"])

def _fmt(f, v):
    w = f["width"]
    if f["kind"] != "numeric":
        if not isinstance(v, str) or len(v) > w:
            return "!" * w
        return v.ljust(w)
    if isinstance(v, bool) or not isinstance(v, (int, Decimal)):
        return "!" * w
    d = Decimal(v)
    if not d.is_finite():
        return "!" * w
    if d < 0 and not f["signed"]:
        return "!" * w
    q = d.copy_abs().scaleb(f["scale"])
    if q != q.to_integral_value() or q >= Decimal(10) ** (f["digits"] + f["scale"]):
        return "!" * w
    digits = str(int(q)).rjust(f["digits"] + f["scale"], "0")
    if f["signed"]:
        return ("-" if d < 0 and q != 0 else "+") + digits
    return digits

def main():
    from {target} import {func} as entry
    rc = 0
    for raw in sys.stdin:
        line = raw.rstrip("\n").rstrip("\r").ljust({length})
        dicts = {{p: {{}} for p in PARAMS}}
        pos = 0
        for f in SPEC:
            dicts[f["param"]][f["key"]] = _parse(f, line[pos:pos + f["width"]])
            pos += f["width"] + 1
        ret = entry(*[dicts[p] for p in PARAMS])
        if isinstance(ret, int) and not isinstance(ret, bool):
            rc = ret
        out = []
        for f in SPEC:
            out.append(_fmt(f, dicts[f["param"]].get(f["key"])))
        sys.stdout.write("|".join(out) + "\n")
    sys.stdout.flush()
    return rc

if __name__ == "__main__":
    sys.exit(main() & 0xFF)
'''

HARNESS_MAIN = r'''# Generated by LegacyBridge - runner for main program {module}. Do not edit.
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.setrecursionlimit(10000)

if __name__ == "__main__":
    from {target} import main as entry
    rc = entry()
    sys.stdout.flush()
    sys.exit((rc if isinstance(rc, int) and not isinstance(rc, bool) else 0) & 0xFF)
'''


def generate_harness(module: str, kind: str, layout: Layout, target: str) -> str:
    """Python source of the harness that runs translated `module` on driver-format stdin."""
    if kind != "subprogram":
        return HARNESS_MAIN.format(module=module, target=target)
    rec = layout.records[0]
    spec = []
    for f, (param, key) in zip(rec.fields, param_keys(layout)):
        spec.append({"param": param, "key": key, "kind": "numeric" if f.numeric else "alnum",
                     "width": f.width, "digits": f.f.int_digits, "scale": f.f.scale, "signed": f.f.signed})
    return HARNESS_CALL.format(module=module, spec=pprint.pformat(spec, width=110, sort_dicts=False), params=repr(layout.params),
                               target=target, func=target, length=rec.length)
